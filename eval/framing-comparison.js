#!/usr/bin/env node
/**
 * Secondary analysis: cross-outlet framing comparison (thesis 8.7).
 *
 *   node eval/framing-comparison.js [--detections eval/out/detections.json] [--out eval/reports]
 *
 * The framing set (6.3) is five news events (News 1 to News 5), each covered by one Left, one
 * Center and one Right outlet: articles L01-L05, C01-C05, R01-R05 (same number = same event).
 * For each article it reports (8.7) the count of detected bias cues and the count per technique,
 * using only the full pipeline's rendered highlights from eval/generate-sheet.js. Descriptive
 * statistics only; this is not a measure of detection performance. Highlights per 1,000 words
 * are added because the three articles of an event differ in length.
 * Writes framing-comparison.json and framing-comparison.md.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : def;
};
const DETECTIONS = opt("--detections", path.join(__dirname, "out", "detections.json"));
const OUT = opt("--out", path.join(__dirname, "reports"));

const catalog = JSON.parse(fs.readFileSync(path.join(__dirname, "../data/pattern-catalog.json"), "utf8").replace(/^﻿/, ""));
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, "corpus-manifest.json"), "utf8"));
const GROUPS = [["L", "Left"], ["C", "Center"], ["R", "Right"]];
const EVENTS = [1, 2, 3, 4, 5];

function run(detections) {
  if (detections.catalogVersion !== catalog.catalogVersion) {
    throw new Error("detections.json was made with catalog " + detections.catalogVersion + ", current is " + catalog.catalogVersion + ": re-run eval/generate-sheet.js");
  }
  const techniques = Object.keys(catalog.techniques);
  const words = {};
  manifest.articles.forEach((a) => (words[a.id] = a.words));
  const shown = detections.items.filter((it) => it.inFullPipeline);

  const articles = [];
  EVENTS.forEach((n) => {
    GROUPS.forEach(([g, lean]) => {
      const id = g + String(n).padStart(2, "0");
      const meta = manifest.articles.find((a) => a.id === id);
      if (!meta) throw new Error("framing-set article " + id + " is missing from the corpus manifest");
      const hits = shown.filter((it) => it.articleId === id);
      const perTechnique = {};
      techniques.forEach((t) => (perTechnique[t] = hits.filter((h) => h.technique === t).length));
      articles.push({
        event: n,
        id: id,
        lean: lean,
        title: meta.title,
        words: words[id],
        cues: hits.length,
        per1000Words: words[id] ? (hits.length * 1000) / words[id] : null,
        perTechnique: perTechnique,
        phrases: hits.map((h) => ({ phrase: h.phrase, technique: h.technique, rule: h.patternId }))
      });
    });
  });

  const byLean = GROUPS.map(([, lean]) => {
    const list = articles.filter((a) => a.lean === lean);
    const w = list.reduce((s, a) => s + a.words, 0);
    const cues = list.reduce((s, a) => s + a.cues, 0);
    const perTechnique = {};
    techniques.forEach((t) => (perTechnique[t] = list.reduce((s, a) => s + a.perTechnique[t], 0)));
    const counts = list.map((a) => a.cues);
    const mean = cues / list.length;
    const sd = Math.sqrt(counts.reduce((s, c) => s + (c - mean) ** 2, 0) / (counts.length - 1));
    return { lean: lean, articles: list.length, words: w, cues: cues, meanPerArticle: mean, sdPerArticle: sd, per1000Words: (cues * 1000) / w, articlesWithNoCue: list.filter((a) => a.cues === 0).length, perTechnique: perTechnique };
  });

  return { generatedAt: new Date().toISOString(), catalogVersion: catalog.catalogVersion, detectionsGeneratedAt: detections.generatedAt, articles: articles, byLean: byLean };
}

function toMarkdown(r) {
  const label = (t) => catalog.techniques[t].label;
  const f1 = (x) => (x === null ? "n/a" : x.toFixed(2));
  const L = ["# Cross-outlet framing comparison (thesis 8.7)", "",
    "Catalog " + r.catalogVersion + "; full-pipeline highlights from detections.json (" + r.detectionsGeneratedAt.slice(0, 10) + "). Generated by `node eval/framing-comparison.js`. Descriptive statistics only.", "",
    "## Per article", "", "| News | Article | Lean | Words | Cues | Per 1,000 words | Techniques (count) | Phrases |", "|---|---|---|---|---|---|---|---|"];
  r.articles.forEach((a) => {
    const t = Object.keys(a.perTechnique).filter((k) => a.perTechnique[k]).map((k) => label(k) + " (" + a.perTechnique[k] + ")").join("; ") || "-";
    const p = a.phrases.map((x) => "\"" + x.phrase + "\" (" + x.rule + ")").join("; ") || "-";
    L.push("| " + ["News " + a.event, a.id, a.lean, a.words, a.cues, f1(a.per1000Words), t, p].join(" | ") + " |");
  });
  L.push("", "## By outlet group (15 articles, 5 per group)", "", "| Group | Words | Cues | Mean per article (SD) | Per 1,000 words | Articles with no cue |", "|---|---|---|---|---|---|");
  r.byLean.forEach((g) => L.push("| " + [g.lean, g.words, g.cues, f1(g.meanPerArticle) + " (" + f1(g.sdPerArticle) + ")", f1(g.per1000Words), g.articlesWithNoCue + " of " + g.articles].join(" | ") + " |"));
  const used = Object.keys(r.byLean[0].perTechnique).filter((t) => r.byLean.some((g) => g.perTechnique[t]));
  L.push("", "## Techniques by outlet group", "", "| Technique | " + r.byLean.map((g) => g.lean).join(" | ") + " |", "|---|" + r.byLean.map(() => "---").join("|") + "|");
  used.forEach((t) => L.push("| " + label(t) + " | " + r.byLean.map((g) => g.perTechnique[t]).join(" | ") + " |"));
  L.push("", "Techniques not detected in any framing-set article: " + (Object.keys(r.byLean[0].perTechnique).filter((t) => !used.includes(t)).map(label).join(", ") || "none") + ".");
  return L.join("\n") + "\n";
}

function main() {
  const r = run(JSON.parse(fs.readFileSync(DETECTIONS, "utf8")));
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, "framing-comparison.json"), JSON.stringify(r, null, 2) + "\n");
  const md = toMarkdown(r);
  fs.writeFileSync(path.join(OUT, "framing-comparison.md"), md);
  console.log(md);
}

if (require.main === module) main();

module.exports = { run: run, toMarkdown: toMarkdown };
